def build_blocks(p: dict) -> str:
    """問題文を上から順に並べる形（第2回から）。

    第1回は「前置き → 図 → 小問」の決まった形だったので head/lead/img/items で足りたが、
    第2回は図が問題文の途中に入ったり、小問の中に数式が入ったりするので、
    問題文の並び順をそのまま書けるように部品の列で持つ。
      ("p", html)          段落
      ("img", file, alt)   図（exercises/img/ のファイル名）
      ("eq", tex)          別行立ての数式（$$ $$ で囲む）
      ("h3", text)         小見出し（問題4-1 など）
      ("ol", [html, ...])  番号つきの小問
      ("ul", [html, ...])  箇条書き。要素は文字列か、部品の列（数式を含む項目）
    """
    def render(blocks: list, ind: str) -> list[str]:
        out = []
        for b in blocks:
            kind = b[0]
            if kind == "p":
                out.append(f'{ind}<p class="lead">{b[1]}</p>')
            elif kind == "img":
                out.append(f'{ind}<figure><img src="img/{b[1]}" alt="{b[2]}"></figure>')
            elif kind == "eq":
                out.append(f'{ind}<div class="eq">$${b[1]}$$</div>')
            elif kind == "h3":
                out.append(f"{ind}<h3>{b[1]}</h3>")
            elif kind in ("ol", "ul"):
                out.append(f"{ind}<{kind}>")
                for it in b[1]:
                    if isinstance(it, str):
                        out.append(f"{ind}  <li>{it}</li>")
                    else:
                        out.append(f"{ind}  <li>")
                        out.extend(render(it, ind + "    "))
                        out.append(f"{ind}  </li>")
                out.append(f"{ind}</{kind}>")
            else:
                raise SystemExit(f"知らない部品: {kind}")
        return out

    inner = "\n".join(render(p["blocks"], "      "))
    return f"""    <section class="q">
      <h2>{p['head']}</h2>
{inner}
    </section>"""


