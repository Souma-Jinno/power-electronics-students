def _rounds_label(nums: list[int]) -> str:
    """[4, 5, 6, 7, 9, 10, 14] → 「第4〜7回・第9回・第10回・第14回」（2つ以上続く回は 〜 でまとめる）"""
    parts, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        parts.append(f"第{nums[i]}〜{nums[j]}回" if j - i >= 2 else "・".join(f"第{k}回" for k in nums[i:j + 1]))
        i = j + 1
    return "・".join(parts)


def _ltspice_src() -> str | None:
    import re
    src = ROOT / "ltspice" / "_page_src.html"
    if not src.exists():
        return None
    s = src.read_text(encoding="utf-8")
    return re.sub(r"<!-- LTspice のページの元.*?-->\n", "", s, count=1, flags=re.S)   # 元のファイルだけの注記


def ltspice_rows() -> list[tuple[int, str, str, str]]:
    """_page_src.html の回の一覧の表から（回, 回の表記, テーマ, 入っている回路）。学生用トップの表と回のページの見出しに使う。"""
    import re
    s = _ltspice_src() or ""
    return [(int(m.group(4)), m.group(1), m.group(2), m.group(3)) for m in re.finditer(
        r'<tr><td class="n">(.*?)</td><td>(.*?)</td><td>(.*?)</td><td><a href="(\d\d)\.html">', s)]


def build_ltspice_pages() -> dict[str, str]:
    """ltspice/_page_src.html（全部の回が入った元）から ltspice/index.html と回ごとのページ ltspice/NN.html を作る。
    LTSPICE に入っていない回（公開版でチェックの無い回）は、回の一覧の行を消し、回のページも作らない。
    消さないと一覧から zip へたどれてしまい、公開版に入ってしまう（publish_from_checks の crawl はリンクをたどって公開するファイルを決める）。"""
    import re
    s = _ltspice_src()
    if s is None:
        return {}
    keep = set(LTSPICE)
    info = {n: (label, theme) for n, label, theme, _ in ltspice_rows()}
    sec = lambda tag: re.compile(rf"[ \t]*<!-- {tag} -->.*?<!-- /{tag} -->\n", re.S)
    rounds_re = re.compile(r"[ \t]*<!-- ltspice:(\d\d) -->.*?<!-- /ltspice:\1 -->\n", re.S)

    def fill(t: str, **kw: str) -> str:
        for k, v in kw.items():
            t = t.replace("{{" + k + "}}", v)
        return t

    pages = {}
    # 一覧のページ：回の節と回のページだけの案内を消し、チェックの無い回の行を消す
    t = rounds_re.sub("", sec("round:only").sub("", s))
    t = re.sub(r"[ \t]*<!-- /?index:only -->\n", "", t)
    t = "".join(line for line in t.splitlines(keepends=True)
                if not (m := re.search(r'<tr>.*href="(\d\d)\.html"', line)) or int(m.group(1)) in keep)
    # 副題の回の並び。8 番の zip は第8回の枠に置いた「参考」（B級増幅）なので並びには入れない
    rounds = _rounds_label(sorted(k for k in keep if k != 8))
    pages["index.html"] = fill(
        t, TITLE="LTspice の回路ファイル", H1="LTspice の回路ファイル",
        SUBTITLE=f"パワーエレクトロニクス {rounds} / 大阪工業大学" if rounds else "パワーエレクトロニクス / 大阪工業大学",
        NAV='<a href="../index.html">← 科目のページへ戻る</a><a href="../sim/index.html">回路のシミュレーター（ブラウザ版）</a>')
    # 回のページ：その回の節だけ残す
    for n in sorted(keep):
        if n not in info:
            print(f"警告: ltspice/_page_src.html の回の一覧に第{n}回の行が無い（回のページを作らない）")
            continue
        label, theme = info[n]
        t = rounds_re.sub(lambda m: m.group(0) if int(m.group(1)) == n else "", sec("index:only").sub("", s))
        t = re.sub(r"[ \t]*<!-- (/?round:only|/?ltspice:\d\d|===== .* =====) -->\n", "", t)
        t = re.sub(r"\n{3,}", "\n\n", t)
        pages[f"{n:02d}.html"] = fill(
            t, TITLE=f"{label} LTspice", H1=f"{label}　LTspice の回路ファイル",
            SUBTITLE=f"パワーエレクトロニクス {label} {theme} / 大阪工業大学",
            NAV='<a href="../index.html">← 科目のページへ戻る</a><a href="index.html">LTspice の入れ方・回の一覧</a>'
                '<a href="../sim/index.html">回路のシミュレーター（ブラウザ版）</a>')
    return pages


